import { actionCode, HELPERS, elementCode, q, type Helper } from "./auto.js";
import type { VerifyFile } from "./verifyFile.js";

/**
 * `ashiato export-tests`: a verification (`checks/*.verify.md`) as a Playwright test using
 * `ashiato/playwright`. Each step becomes a `test.step` that does the step's actions and checks with
 * `expectDbChanges` the changes the step expects, written as the file has them. Elements are found
 * as `verify --auto` finds them (the same helpers), so a file that passes there passes here.
 */
export interface ExportOptions {
  /** The verification's file, for the header. */
  fileName: string;
  /** The app's URL: the test's baseURL. Without it, the config's baseURL is used. */
  app?: string;
  /** `test.use({ ashiato: { tables, ignoreColumns } })`. */
  tables?: string[];
  ignoreColumns?: string[];
  /** A login saved by `verify --login` (Playwright's storage state). */
  storageState?: string;
  /** The test's title (default: the file's `# ` heading). */
  name?: string;
}

/** The header every file `export-tests` writes starts with: it overwrites only such files. */
export const EXPORTED_HEADER = "// Generated by `ashiato export-tests`";

export interface ExportedTest {
  code: string;
  /** Steps with actions, and steps a person does (left out of the test as comments). */
  automated: number;
  manual: string[];
}

/** A comment on one line. */
const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();

export function exportTest(file: VerifyFile, options: ExportOptions): ExportedTest {
  const helpers = new Set<Helper>();
  let usesExpect = false;
  const manual: string[] = [];
  let automated = 0;
  /** A step before gave dialogs answers: they are not the next step's (as `verify --auto` does). */
  let answered = false;
  const body: string[] = [];
  const emit = (line = "", depth = 1) => body.push(line ? `${"  ".repeat(depth)}${line}` : "");

  for (const step of file.steps) {
    emit();
    if (!step.actions) {
      manual.push(step.title);
      emit(`// ${oneLine(step.title)}: a person does this step (it has no actions), so the test leaves it out. TODO:`);
      for (const l of step.body.split("\n").filter((l) => l.trim())) emit(`//   ${oneLine(l)}`);
      if (step.expect) for (const l of step.expect.lines) emit(`//   expected: ${oneLine(l)}`);
      continue;
    }
    automated++;
    const run: string[] = [];
    for (const a of step.actions) {
      const el = elementCode(a);
      if (el?.helper) helpers.add(el.helper);
      if (a.verb === "wait" || a.verb === "expect") usesExpect ||= a.ms === undefined;
      run.push(...actionCode(a));
    }
    emit(`await test.step(${q(step.title)}, async () => {`);
    if (answered) emit("dialogs.length = 0;", 2);
    answered ||= step.actions.some((a) => a.verb === "dialog");
    if (step.expect) {
      emit("await expectDbChanges(async () => {", 2);
      for (const l of run) emit(l, 3);
      emit("}, [", 2);
      for (const l of step.expect.lines) emit(`${q(l)},`, 3);
      emit("]);", 2);
    } else {
      emit("// no expected changes written: what changes isn't checked", 2);
      for (const l of run) emit(l, 2);
    }
    emit("});");
  }

  const dialogs = [
    "// dialogs are answered as the steps say (`dialog: Cancel`), else with OK, as `ashiato verify --auto` does",
    "const dialogs: (boolean | string)[] = [];",
    'page.on("dialog", (dialog) => {',
    "  const answer = dialogs.shift() ?? true;",
    '  void (answer === false ? dialog.dismiss() : dialog.accept(typeof answer === "string" ? answer : undefined));',
    "});",
  ];
  const ashiato = [
    ...(options.tables?.length ? [`tables: [${options.tables.map(q).join(", ")}]`] : []),
    ...(options.ignoreColumns?.length ? [`ignoreColumns: [${options.ignoreColumns.map(q).join(", ")}]`] : []),
  ];
  const use = [
    ...(options.app ? [`baseURL: ${q(options.app)},`] : []),
    ...(options.storageState ? [`storageState: ${q(options.storageState)}, // the login saved by \`ashiato verify --auto --login\``] : []),
    ...(ashiato.length ? [`ashiato: { ${ashiato.join(", ")} },`] : []),
  ];
  const title = options.name ?? (file.title || options.fileName.replace(/^.*[\\/]/, "").replace(/\.verify\.md$/i, ""));
  const lines = [
    `${EXPORTED_HEADER} from ${options.fileName}: export it again after changing that file, or change this one by hand from now on.`,
    "// It does each step's actions and checks with expectDbChanges what they changed in the database, as `ashiato verify --auto` does.",
    "// Before running it:",
    options.app ? `// - start the app (${options.app}),` : "// - start the app, and set baseURL in playwright.config to its URL,",
    "// - set ASHIATO_DB_URL to the test database (read-only access is enough), in the state the steps start from,",
    "// - run tests that check the database one at a time: npx playwright test --workers=1",
    ...(manual.length ? [`// ${manual.length} step(s) a person does are left out (marked TODO).`] : []),
    `import { test${usesExpect ? ", expect" : ""} } from "ashiato/playwright";`,
    ...(helpers.size ? ['import type { Locator, Page } from "@playwright/test";'] : []),
    "",
    ...(use.length ? ["test.use({", ...use.map((u) => `  ${u}`), "});", ""] : []),
    ...(["clickable", "field", "checkable", "ofRoles"] as const).filter((h) => helpers.has(h)).flatMap((h) => [HELPERS[h], ""]),
    `test(${q(title)}, async ({ page, expectDbChanges }) => {`,
    ...dialogs.map((l) => `  ${l}`),
    ...body,
    "});",
  ];
  return { code: `${lines.join("\n")}\n`, automated, manual };
}
